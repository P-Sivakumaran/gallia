export function listPortals(): PortalInfo[] {
  return Object.values(LISTED_CLUB_PORTALS)
}

export function getPortal(id: string): PortalInfo | undefined {
  return LISTED_CLUB_PORTALS[id]
}

export function getChannel(id: string): FilingChannel | undefined {
  return FILING_CHANNELS[id]
}

/** The access status of the channel a portal is read through. */
export function portalAccess(portalId: string): ChannelAccess {
  const portal = LISTED_CLUB_PORTALS[portalId]
  return portal ? (FILING_CHANNELS[portal.channelId]?.access ?? 'UNKNOWN') : 'UNKNOWN'
}
